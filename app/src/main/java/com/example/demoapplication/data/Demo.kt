class TestEquals(val id: Int, val name: String) {
    var hashCodeCallCount = 0
    var equalsCallCount = 0
    
    override fun equals(other: Any?): Boolean {
        equalsCallCount++
        println("  → equals() called (call #$equalsCallCount)")
        println("  → equals() does NOT call hashCode() - they're independent!")
        
        if (this === other) return true
        if (other !is TestEquals) return false
        
        // equals() compares properties directly - NO hashCode() call!
        return id == other.id && name == other.name
    }
    
    override fun hashCode(): Int {
        hashCodeCallCount++
        println("  → hashCode() called (call #$hashCodeCallCount)")
        return id.hashCode() * 31 + name.hashCode()
    }
}

fun demonstrateEqualsAndHashCodeIndependence() {
    println("""
        COMMON MISCONCEPTION:
        Many people think equals() internally uses hashCode() to determine equality.
        
        TRUTH:
        equals() and hashCode() are COMPLETELY INDEPENDENT methods!
        equals() does NOT call hashCode() internally.
    """.trimIndent())
    
    println("\n--- Proof: equals() Works Without hashCode() ---")
    val obj1 = TestEquals(1, "Alice")
    val obj2 = TestEquals(1, "Alice")
    
    println("Comparing obj1 == obj2:")
    val result = obj1 == obj2
    println("Result: $result")
    println("equals() was called ${obj1.equalsCallCount} time(s)")
    println("hashCode() was called ${obj1.hashCodeCallCount} time(s)")
    println("→ equals() did NOT call hashCode()!")
    
    println("\n--- When Does hashCode() Get Called? ---")
    println("""
        hashCode() is called by COLLECTIONS (HashMap, HashSet, etc.), NOT by equals():
        
        1. HashMap.put(key, value):
           - Calls key.hashCode() → finds bucket
           - Stores in that bucket
           
        2. HashMap.get(key):
           - Calls key.hashCode() → finds bucket (FAST lookup)
           - Then calls equals() on objects in that bucket (to verify exact match)
           
        3. HashSet.contains(element):
           - Calls element.hashCode() → finds bucket
           - Then calls equals() to verify
           
        Process:
        hashCode() → Find bucket (FAST, O(1))
        equals() → Verify exact match (slower, but accurate)
    """.trimIndent())
    
    println("\n--- Demonstration: HashMap Usage ---")
    val map = mutableMapOf<TestEquals, String>()
    val key1 = TestEquals(1, "Alice")
    val key2 = TestEquals(1, "Alice")  // Same id and name
    
    println("\n1. Adding key1 to map:")
    map[key1] = "Value 1"
    println("   hashCode() called: ${key1.hashCodeCallCount} time(s)")
    println("   equals() called: ${key1.equalsCallCount} time(s)")
    
    println("\n2. Getting value with key2:")
    val value = map[key2]
    println("   Result: $value")
    println("   hashCode() called: ${key2.hashCodeCallCount} time(s)")
    println("   equals() called: ${key2.equalsCallCount} time(s)")
    println("   → HashMap calls hashCode() FIRST, then equals() to verify!")
    
    println("\n--- The Contract (Not Implementation) ---")
    println("""
        The relationship between equals() and hashCode() is a CONTRACT, not implementation:
        
        CONTRACT:
        If a.equals(b) == true, then a.hashCode() == b.hashCode()
        
        This means:
        - equals() does NOT call hashCode() internally
        - They are independent methods
        - But they MUST be consistent (follow the contract)
        - Collections use hashCode() for performance, equals() for accuracy
        
        Why the contract exists:
        - Collections use hashCode() to find the right "bucket" quickly
        - Then use equals() to find the exact match in that bucket
        - If contract is broken, collections malfunction!
    """.trimIndent())
    
    println("\n--- Example: What Happens When Contract is Broken ---")
    class BrokenContract(val id: Int, val name: String) {
        override fun equals(other: Any?): Boolean {
            return id == (other as? BrokenContract)?.id  // Only compares id
        }
        
        override fun hashCode(): Int {
            return id.hashCode() * 31 + name.hashCode()  // Uses id + name!
            // ❌ PROBLEM: equals() uses only id, hashCode() uses id + name
        }
    }
    
    val broken1 = BrokenContract(1, "Alice")
    val broken2 = BrokenContract(1, "Bob")  // Same id, different name
    
    println("broken1 == broken2: ${broken1 == broken2}")  // true (same id)
    println("broken1.hashCode(): ${broken1.hashCode()}")
    println("broken2.hashCode(): ${broken2.hashCode()}")
    println("hashCodes equal: ${broken1.hashCode() == broken2.hashCode()}")  // false!
    
    val brokenMap = mutableMapOf<BrokenContract, String>()
    brokenMap[broken1] = "Found"
    println("\nMap contains broken1: ${brokenMap.containsKey(broken1)}")
    println("Map contains broken2: ${brokenMap.containsKey(broken2)}")  // Might be false!
    println("→ Even though equals() says they're equal, HashMap might not find it!")
    println("→ This is because hashCode() differs, so it looks in wrong bucket!")
    
    println("\n--- Summary ---")
    println("""
        ✅ equals() does NOT use hashCode() internally
        ✅ They are completely independent methods
        ✅ equals() compares properties directly
        ✅ hashCode() is used by collections for performance (bucket lookup)
        ✅ Collections call hashCode() FIRST, then equals() to verify
        
        The Contract:
        - If equals() returns true, hashCode() MUST be equal
        - This is a requirement, not an implementation detail
        - Breaking the contract causes collections to malfunction
        
        Remember:
        - equals() = "Are these objects equal?" (compares properties)
        - hashCode() = "Which bucket should this go in?" (used by collections)
        - They work together but are independent!
    """.trimIndent())
}

