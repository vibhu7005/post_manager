fun demonstrateContractFailureWithInheritance() {
    println("""
        YES! Contract failure CAN happen in regular classes with inheritance too!
        
        The same base/derived problem exists, but:
        - Regular classes: You manually implement equals()/hashCode() → you can fix it
        - Data classes: Auto-generated → compiler can't fix it automatically
    """.trimIndent())
    
    println("\n--- Example: Regular Base/Derived with Contract Violation ---")
    
    // Base class
    open class BaseEmployee(val id: Int) {
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (other !is BaseEmployee) return false
            return id == other.id  // Only compares id
        }
        
        override fun hashCode(): Int {
            return id.hashCode()  // Uses only id
        }
    }
    
    // Derived class
    class DerivedEmployee(id: Int, val department: String) : BaseEmployee(id) {
        // Problem: Should we override equals()?
        // Option 1: Don't override → uses parent's equals() (only compares id)
        // Option 2: Override → compares id + department
        
        // Let's try Option 1 (don't override equals)
        // This means equals() only compares id, but hashCode()...
        
        override fun hashCode(): Int {
            return id.hashCode() * 31 + department.hashCode()  // Uses id + department!
            // ❌ PROBLEM: equals() uses only id (from parent), hashCode() uses id + department
        }
    }
    
    val base1 = BaseEmployee(1)
    val derived1 = DerivedEmployee(1, "Engineering")
    val derived2 = DerivedEmployee(1, "Marketing")  // Same id, different department
    
    println("base1 == derived1: ${base1 == derived1}")  // true (same id)
    println("derived1 == derived2: ${derived1 == derived2}")  // true (same id)
    
    println("base1.hashCode(): ${base1.hashCode()}")
    println("derived1.hashCode(): ${derived1.hashCode()}")
    println("derived2.hashCode(): ${derived2.hashCode()}")
    
    println("base1.hashCode() == derived1.hashCode(): ${base1.hashCode() == derived1.hashCode()}")  // false!
    println("derived1.hashCode() == derived2.hashCode(): ${derived1.hashCode() == derived2.hashCode()}")  // false!
    
    println("❌ CONTRACT VIOLATION!")
    println("❌ equals() returns true, but hashCodes differ!")
    println("❌ This happens because equals() uses only id, but hashCode() uses id + department")
    
    println("\n--- Consequences: HashMap Breaks ---")
    val empMap = mutableMapOf<BaseEmployee, String>()
    empMap[base1] = "Base employee"
    println("Added: BaseEmployee(1)")
    
    val retrieved1 = empMap[derived1]
    val retrieved2 = empMap[derived2]
    println("Getting DerivedEmployee(1, 'Engineering'): $retrieved1")
    println("Getting DerivedEmployee(1, 'Marketing'): $retrieved2")
    println("→ HashMap might not find them even though equals() says they're equal!")
    
    println("\n--- Example: Trying to Fix It (Still Problematic) ---")
    
    // Try to fix by overriding equals() in Derived
    class FixedDerivedEmployee(id: Int, val department: String) : BaseEmployee(id) {
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (other !is FixedDerivedEmployee) return false
            return id == other.id && department == other.department  // Compares both
        }
        
        override fun hashCode(): Int {
            return id.hashCode() * 31 + department.hashCode()  // Uses both
        }
    }
    
    val fixed1 = FixedDerivedEmployee(1, "Engineering")
    val fixed2 = FixedDerivedEmployee(1, "Marketing")
    
    println("fixed1 == fixed2: ${fixed1 == fixed2}")  // false (different departments)
    println("fixed1.hashCode() == fixed2.hashCode(): ${fixed1.hashCode() == fixed2.hashCode()}")  // false
    
    // But what about comparing BaseEmployee with FixedDerivedEmployee?
    val base2 = BaseEmployee(1)
    println("base2 == fixed1: ${base2 == fixed1}")  // false (different types)
    println("→ Now equals() is consistent, but inheritance still causes confusion!")
    
    println("\n--- The Real Problem with Inheritance ---")
    println("""
        When you have Base and Derived classes:
        
        Problem 1: Should Base(1) == Derived(1, "extra")?
        - Same id → maybe true?
        - But Derived has extra property → maybe false?
        
        Problem 2: If equals() returns true, hashCode() MUST be equal
        - Base(1).hashCode() = hash(id=1)
        - Derived(1, "extra").hashCode() = hash(id=1, extra="extra")
        - These are DIFFERENT! → Contract violation!
        
        Problem 3: Even if you fix it manually:
        - You have to decide: compare all properties or just some?
        - Different derived classes might need different logic
        - It becomes complex and error-prone
        
        Regular Classes:
        - You CAN manually fix it (but it's complex)
        - You have full control
        - But it's easy to make mistakes
        
        Data Classes:
        - Auto-generate equals()/hashCode() based on ALL properties
        - Can't know how to handle inheritance automatically
        - Would always generate inconsistent code
        - So Kotlin prevents inheritance entirely
    """.trimIndent())
    
    println("\n--- Why Data Classes Can't Be Inherited (Summary) ---")
    println("""
        The contract violation problem EXISTS in regular classes too!
        
        But the difference is:
        
        Regular Classes:
        ✅ Can be inherited
        ✅ You manually implement equals()/hashCode()
        ✅ You can (try to) fix contract violations manually
        ⚠️ But it's complex and error-prone
        
        Data Classes:
        ❌ Cannot be inherited
        ❌ Auto-generate equals()/hashCode()
        ❌ Compiler can't know how to handle inheritance
        ✅ Prevents the problem entirely by making them final
        
        The Real Reason:
        - Not that contract violation is unique to data classes
        - But that data classes auto-generate code
        - Auto-generated code can't handle inheritance correctly
        - So Kotlin prevents inheritance to avoid the problem
    """.trimIndent())
}

