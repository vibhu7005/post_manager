/*
 * PROBLEM 1: equals() and hashCode() Contract Violation
 * 
 * Data classes automatically generate equals() and hashCode() based on ALL properties.
 * If inheritance were allowed, we'd have this problem:
 */

// This is what WOULD happen if data classes could be inherited (but it's NOT allowed):
/*
data class Base(val id: Int)
class Derived(val id: Int, val extra: String) : Base(id)

// Problem: Should Base(1) equal Derived(1, "extra")?
// - They have the same 'id'
// - But Derived has additional 'extra' property
// - equals() contract: if a == b, then a.hashCode() == b.hashCode()
// - But Base(1).hashCode() != Derived(1, "extra").hashCode()
// - This BREAKS the contract!
*/

fun demonstrateWhyDataClassesCannotBeInherited() {
    println("""
        Data classes automatically generate:
        1. equals() - compares ALL properties structurally
        2. hashCode() - based on ALL properties  
        3. toString() - includes ALL properties
        4. copy() - copies ALL properties
        5. componentN() - destructuring for ALL properties
        
        If inheritance were allowed, these would break. Let's see why:
    """.trimIndent())
    
    // Show what happens with regular classes that CAN be inherited
    println("\n--- Example 1: Regular Classes CAN Be Inherited ---")
    open class RegularBase(val id: Int)
    class RegularDerived(id: Int, val extra: String) : RegularBase(id)
    
    val base = RegularBase(1)
    val derived = RegularDerived(1, "extra")
    
    println("base == derived: ${base == derived}")  // false (uses default equals = referential)
    println("base === derived: ${base === derived}")  // false
    println("→ Regular classes can be inherited, but equals() is NOT auto-generated")
    println("→ You must manually implement equals()/hashCode() if needed")
    
    // Now show what WOULD break if data classes could be inherited
    println("\n--- Problem 1: equals() and hashCode() Contract Violation ---")
    println("""
        If this were allowed (but it's NOT):
        
        data class Base(val id: Int)
        class Derived(val id: Int, val extra: String) : Base(id)
        
        Question: Should Base(1) == Derived(1, "extra")?
        
        Data class equals() compares ALL properties:
        - Base(1) has: id=1
        - Derived(1, "extra") has: id=1, extra="extra"
        - Are they equal? Same id, but different properties!
        
        hashCode() problem:
        - Base(1).hashCode() = hash(id=1)
        - Derived(1, "extra").hashCode() = hash(id=1, extra="extra")
        - These are DIFFERENT!
        
        CONTRACT VIOLATION:
        If equals() returns true, hashCode() MUST be equal!
        But Base(1).hashCode() != Derived(1, "extra").hashCode()
        → This BREAKS the contract!
        → Collections (HashMap, HashSet) would malfunction!
    """.trimIndent())
    
    // Demonstrate the contract violation with a practical example
    println("\n--- Practical Example: What Would Break ---")
    
    // Simulate what would happen (using regular classes to show the concept)
    class SimulatedBase(val id: Int) {
        // Simulate data class equals() - compares all properties
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (other !is SimulatedBase) return false
            return id == other.id  // Only compares id (Base only has id)
        }
        
        override fun hashCode(): Int = id.hashCode()
    }
    
    class SimulatedDerived(id: Int, val extra: String) : SimulatedBase(id) {
        // If this were a data class, equals() would compare id + extra
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (other !is SimulatedDerived) return false
            return id == other.id && extra == other.extra  // Compares BOTH
        }
        
        override fun hashCode(): Int = id.hashCode() * 31 + extra.hashCode()
    }
    
    val simBase = SimulatedBase(1)
    val simDerived = SimulatedDerived(1, "extra")
    
    println("simBase == simDerived: ${simBase == simDerived}")  // false (different types)
    println("simBase.hashCode(): ${simBase.hashCode()}")
    println("simDerived.hashCode(): ${simDerived.hashCode()}")
    println("→ Even with manual implementation, inheritance causes confusion")
    
    println("\n--- Problem 2: copy() Ambiguity ---")
    println("""
        If Derived could inherit from data class Base:
        
        val derived = Derived(1, "extra")
        val copied = derived.copy()  // What should this return?
        
        Options:
        1. Base instance? → loses 'extra' property ❌
        2. Derived instance? → but copy() is from Base ❌
        3. Which properties should be copied? ❌
        
        → copy() signature is tied to constructor parameters
        → Inheritance breaks this contract
    """.trimIndent())
    
    println("\n--- Problem 3: componentN() Confusion ---")
    println("""
        Destructuring would be unclear:
        
        val derived = Derived(1, "extra")
        val (id) = derived  // Which component?
        
        Options:
        1. Just 'id'? → ignores 'extra' ❌
        2. Both 'id' and 'extra'? → but Base only has one component ❌
        
        → componentN() functions are generated based on constructor params
        → Inheritance breaks destructuring
    """.trimIndent())
    
    println("\n--- Problem 4: toString() Inconsistency ---")
    println("""
        Data class toString() includes ALL properties.
        
        If Derived inherits from Base:
        - Should toString() include parent properties?
        - Should toString() include child properties?
        - How to format it consistently?
        
        → toString() generation becomes ambiguous
    """.trimIndent())
    
    println("\n--- SOLUTION: Make Data Classes Final ---")
    println("""
        Kotlin prevents these problems by making data classes 'final' (cannot be inherited).
        
        Benefits:
        ✅ equals() and hashCode() are always consistent
        ✅ copy() always works correctly  
        ✅ componentN() is always clear
        ✅ toString() is always predictable
        ✅ No ambiguity or contract violations
        
        Alternatives if you need inheritance:
        1. Regular classes (not data classes) - can be inherited
        2. Interfaces - for common contracts
        3. Sealed classes - for closed hierarchies
        4. Abstract classes - for common behavior
        5. Composition - "has-a" instead of "is-a"
    """.trimIndent())
    
    println("\n--- Real Example: What Works ---")
    // Show that data classes CAN inherit FROM other classes
    open class Animal(val species: String)
    data class Dog(val name: String, species: String) : Animal(species)
    
    val dog1 = Dog("Buddy", "Canine")
    val dog2 = Dog("Buddy", "Canine")
    println("dog1 == dog2: ${dog1 == dog2}")  // true (structural equality)
    println("dog1.copy(name = 'Max'): ${dog1.copy(name = "Max")}")
    println("→ Data classes CAN inherit FROM other classes (if parent is 'open')")
    println("→ But data classes CANNOT BE inherited FROM (they're final)")
}

