fun demonstrateEqualsHashCodeContract() {
    println("""
        CLARIFICATION:
        
        ❌ MISCONCEPTION: equals() and hashCode() should always return the same result
        
        ✅ TRUTH: 
        - equals() returns Boolean (true/false)
        - hashCode() returns Int
        - They return DIFFERENT types, so they can't "return the same result"
        
        THE CONTRACT:
        If a.equals(b) == true, then a.hashCode() == b.hashCode()
        
        This means:
        - If two objects are equal (equals() returns true), their hashCodes MUST be equal
        - But if two objects are NOT equal (equals() returns false), their hashCodes CAN be equal (hash collision)
        - equals() does NOT call hashCode() internally
    """.trimIndent())
    
    println("\n--- Example 1: Correct Implementation ---")
    
    class Person(val id: Int, val name: String) {
        override fun equals(other: Any?): Boolean {
            return id == (other as? Person)?.id  // Returns Boolean
        }
        
        override fun hashCode(): Int {
            return id.hashCode()  // Returns Int
        }
    }
    
    val person1 = Person(1, "Alice")
    val person2 = Person(1, "Bob")  // Same id
    val person3 = Person(2, "Alice")  // Different id
    
    println("person1 == person2: ${person1 == person2}")  // true
    println("person1.hashCode(): ${person1.hashCode()}")
    println("person2.hashCode(): ${person2.hashCode()}")
    println("person1.hashCode() == person2.hashCode(): ${person1.hashCode() == person2.hashCode()}")  // true ✅
    println("→ When equals() returns true, hashCodes are equal ✅")
    
    println("\nperson1 == person3: ${person1 == person3}")  // false
    println("person3.hashCode(): ${person3.hashCode()}")
    println("person1.hashCode() == person3.hashCode(): ${person1.hashCode() == person3.hashCode()}")  // false
    println("→ When equals() returns false, hashCodes can differ ✅")
    
    println("\n--- Example 2: Hash Collision (Different Objects, Same HashCode) ---")
    println("""
        IMPORTANT: Hash collisions are allowed!
        
        If equals() returns false, hashCode() CAN still be equal.
        This is called a "hash collision" and is normal.
    """.trimIndent())
    
    class SimpleHash(val value: Int) {
        override fun equals(other: Any?): Boolean {
            return value == (other as? SimpleHash)?.value
        }
        
        override fun hashCode(): Int {
            // Simple hash: just return the value
            return value % 10  // Only uses last digit
        }
    }
    
    val obj1 = SimpleHash(1)
    val obj2 = SimpleHash(11)  // Different value, but same hashCode (both % 10 = 1)
    
    println("obj1 == obj2: ${obj1 == obj2}")  // false (different values)
    println("obj1.hashCode(): ${obj1.hashCode()}")
    println("obj2.hashCode(): ${obj2.hashCode()}")
    println("obj1.hashCode() == obj2.hashCode(): ${obj1.hashCode() == obj2.hashCode()}")  // true!
    println("→ Hash collision: Different objects can have same hashCode ✅")
    println("→ This is ALLOWED by the contract!")
    
    println("\n--- The Contract Rules ---")
    println("""
        RULE 1: If equals() returns true → hashCode() MUST be equal
        ✅ person1 == person2 (true) → person1.hashCode() == person2.hashCode() (true)
        
        RULE 2: If equals() returns false → hashCode() CAN be equal (hash collision)
        ✅ obj1 == obj2 (false) → obj1.hashCode() == obj2.hashCode() (true) is OK
        
        RULE 3: equals() does NOT call hashCode() internally
        ✅ They are independent methods
        
        RULE 4: If equals() returns true but hashCode() differs → CONTRACT VIOLATION ❌
        ❌ This breaks collections (HashMap, HashSet, etc.)
    """.trimIndent())
    
    println("\n--- Example 3: Contract Violation ---")
    
    class BrokenPerson(val id: Int, val name: String) {
        override fun equals(other: Any?): Boolean {
            return id == (other as? BrokenPerson)?.id  // Only compares id
        }
        
        override fun hashCode(): Int {
            return id.hashCode() * 31 + name.hashCode()  // Uses id + name!
            // ❌ PROBLEM: equals() uses only id, hashCode() uses id + name
        }
    }
    
    val broken1 = BrokenPerson(1, "Alice")
    val broken2 = BrokenPerson(1, "Bob")  // Same id, different name
    
    println("broken1 == broken2: ${broken1 == broken2}")  // true (same id)
    println("broken1.hashCode(): ${broken1.hashCode()}")
    println("broken2.hashCode(): ${broken2.hashCode()}")
    println("broken1.hashCode() == broken2.hashCode(): ${broken1.hashCode() == broken2.hashCode()}")  // false!
    
    println("❌ CONTRACT VIOLATION!")
    println("❌ equals() returns true, but hashCodes differ!")
    println("❌ This breaks the contract: if equals() == true, hashCode() MUST be equal")
    
    println("\n--- Summary ---")
    println("""
        ✅ equals() does NOT internally use hashCode()
        ✅ equals() returns Boolean, hashCode() returns Int (different types!)
        ✅ They are independent methods
        
        THE CONTRACT:
        - If equals() returns true → hashCode() MUST be equal
        - If equals() returns false → hashCode() CAN be equal (hash collision is OK)
        - If equals() returns true but hashCode() differs → CONTRACT VIOLATION ❌
        
        Remember:
        - equals() = "Are these objects equal?" (Boolean)
        - hashCode() = "Which bucket should this go in?" (Int)
        - They work together but are independent!
        - The contract ensures consistency for collections
    """.trimIndent())
}

