// ============================================================================
// WHY copy() CANNOT BE OVERRIDDEN
// ============================================================================

data class Product(val id: Int, val name: String, val price: Double) {
    // ✅ equals() CAN be overridden (inherited from Any)
    override fun equals(other: Any?): Boolean {
        return id == (other as? Product)?.id
    }
    
    // ✅ hashCode() CAN be overridden (inherited from Any)
    override fun hashCode(): Int {
        return id.hashCode()
    }
    
    // ❌ copy() CANNOT be overridden - this would cause compilation error!
    /*
    override fun copy(id: Int = this.id, name: String = this.name, price: Double = this.price): Product {
        // This is NOT allowed!
        return Product(id, name, price)
    }
    */
    
    // ✅ But you CAN create a custom copy-like function with a different name
    fun customCopy(id: Int = this.id, name: String = this.name, price: Double = this.price): Product {
        return Product(id, name, price)
    }
    
    // ✅ Or create a deep copy function
    fun deepCopy(): Product {
        return Product(this.id, this.name, this.price)
    }
}

fun demonstrateWhyCopyCannotBeOverridden() {
    println("""
        KEY DIFFERENCE:
        - equals() and hashCode() are methods from Any class → can be overridden
        - copy() is a GENERATED function specific to data classes → cannot be overridden
    """.trimIndent())
    
    println("\n--- Why equals() and hashCode() CAN Be Overridden ---")
    println("""
        equals() and hashCode() are methods inherited from Any (root class):
        
        open class Any {
            open operator fun equals(other: Any?): Boolean
            open fun hashCode(): Int
        }
        
        Since they're 'open', they can be overridden in any class, including data classes.
        This allows you to customize equality logic.
    """.trimIndent())
    
    val product1 = Product(1, "Laptop", 999.99)
    val product2 = Product(1, "Desktop", 799.99)  // Same id, different name/price
    
    println("\n--- Example: Overridden equals() ---")
    println("product1 == product2: ${product1 == product2}")  // true (only compares id)
    println("→ equals() was overridden to compare only id")
    
    println("\n--- Why copy() CANNOT Be Overridden ---")
    println("""
        copy() is NOT inherited from Any. It's a GENERATED function:
        
        1. Generated by compiler based on primary constructor parameters
        2. Has a specific signature: copy(param1: Type1 = this.param1, ...)
        3. Returns the same type as the data class
        4. Cannot be overridden because:
           - It's not a virtual method (not in inheritance hierarchy)
           - It's compiler-generated code
           - Overriding would break type safety and contract
    """.trimIndent())
    
    println("\n--- Example: Using copy() ---")
    val original = Product(1, "Laptop", 999.99)
    val copied = original.copy(name = "Gaming Laptop")  // Uses generated copy()
    println("Original: $original")
    println("Copied: $copied")
    println("→ copy() works with default parameters for all constructor params")
    
    println("\n--- What Would Happen If copy() Could Be Overridden? ---")
    println("""
        Problems that would arise:
        
        1. Type Safety Issues:
           - copy() must return the exact same type
           - Overriding could change return type → breaks polymorphism
        
        2. Signature Confusion:
           - copy() signature is tied to constructor parameters
           - Overriding could change parameters → breaks callers
        
        3. Contract Violation:
           - copy() should create a copy with same type
           - Overriding could return different type → breaks expectations
        
        4. Compiler Complexity:
           - copy() is generated at compile time
           - Allowing override would require runtime dispatch → performance cost
    """.trimIndent())
    
    println("\n--- Workaround: Custom Copy Functions ---")
    val product3 = Product(2, "Phone", 599.99)
    val customCopied = product3.customCopy(name = "Smartphone", price = 699.99)
    println("Original: $product3")
    println("Custom copied: $customCopied")
    println("→ You can create custom copy-like functions with different names")
    
    println("\n--- Summary ---")
    println("""
        equals() and hashCode():
        - Inherited from Any class (open methods)
        - Can be overridden ✅
        - Allows customization of equality logic
        
        copy():
        - Generated by compiler (not inherited)
        - Cannot be overridden ❌
        - Signature tied to constructor parameters
        - Ensures type safety and predictable behavior
        
        Workaround:
        - Create custom functions like customCopy(), deepCopy(), etc.
        - These can have different signatures and behavior
        - But they won't be called by the standard copy() syntax
    """.trimIndent())
}

